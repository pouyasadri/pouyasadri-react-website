/**
 * Fetches GitHub pinned repos for pouyasadri and writes content/seed files.
 * Source of truth for case-study stubs: profile pins (HTML), details via REST API.
 *
 * Usage: node scripts/seed-github-pins.mjs
 */
import { writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const root = join(__dirname, "..");
const USER = "pouyasadri";

async function fetchPinnedNames() {
  const html = await fetch(`https://github.com/${USER}`).then((r) => r.text());
  const blocks = html.match(/class="[^"]*pinned-item-list-item[^"]*"[\s\S]*?<\/li>/g) ?? [];
  const names = [];
  for (const block of blocks) {
    const m = block.match(new RegExp(`href="/${USER}/([^"]+)"`));
    if (m?.[1] && !names.includes(m[1])) names.push(m[1]);
  }
  return names;
}

async function fetchRepo(name) {
  const res = await fetch(`https://api.github.com/repos/${USER}/${name}`, {
    headers: { Accept: "application/vnd.github+json", "User-Agent": "pouyasadri-site-seed" },
  });
  if (!res.ok) throw new Error(`GitHub API ${res.status} for ${name}`);
  return res.json();
}

function slugify(name) {
  return name.toLowerCase().replace(/_/g, "-");
}

function buildProject(repo, pinOrder) {
  const slug = slugify(repo.name);
  const desc = (repo.description ?? "").trim() || repo.name;
  return {
    slug,
    title: { fr: repo.name, en: repo.name },
    summary: { fr: desc, en: desc },
    githubUrl: repo.html_url,
    homepage: repo.homepage || null,
    language: repo.language,
    topics: repo.topics ?? [],
    source: "github-pin",
    pinOrder,
    problem: {
      fr: "À rédiger dans Sanity (problème / contexte).",
      en: "To be written in Sanity (problem / context).",
    },
    approach: {
      fr: "À rédiger dans Sanity (architecture / décisions).",
      en: "To be written in Sanity (architecture / decisions).",
    },
    outcome: {
      fr: "À rédiger dans Sanity (résultats / métriques).",
      en: "To be written in Sanity (outcomes / metrics).",
    },
  };
}

const pins = await fetchPinnedNames();
if (pins.length === 0) {
  console.error("No pinned repos found for", USER);
  process.exit(1);
}

const raw = [];
const projects = [];
for (let i = 0; i < pins.length; i++) {
  const name = pins[i];
  const repo = await fetchRepo(name);
  raw.push({
    name: repo.name,
    description: repo.description,
    html_url: repo.html_url,
    homepage: repo.homepage,
    language: repo.language,
    topics: repo.topics ?? [],
    stargazers_count: repo.stargazers_count,
    forks_count: repo.forks_count,
    updated_at: repo.updated_at,
  });
  projects.push(buildProject(repo, i));
  console.log(`✓ ${name}`);
}

const seedDir = join(root, "content/seed");
mkdirSync(seedDir, { recursive: true });
writeFileSync(join(seedDir, "github-pins.json"), JSON.stringify(raw, null, 2) + "\n");
writeFileSync(
  join(seedDir, "projects.json"),
  JSON.stringify(
    {
      _meta: {
        source: `GitHub pinned repositories for ${USER}`,
        profile: `https://github.com/${USER}`,
        fetchedNote: "Generated by scripts/seed-github-pins.mjs",
        pinCount: projects.length,
      },
      projects,
    },
    null,
    2,
  ) + "\n",
);

console.log(`Wrote ${projects.length} project stubs to content/seed/`);
